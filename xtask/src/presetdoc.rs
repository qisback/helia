//! The colour preset table, rendered from `helia_core::colour` so the
//! documentation cannot drift from the code that colours the pictures.

use std::fmt::Write as _;

use helia_core::debayer::Channel;
use helia_core::{ColourParams, Preset};

fn hex(c: [f32; 3]) -> String {
    let b = c.map(|v| (v.clamp(0.0, 1.0) * 255.0).round() as u8);
    format!("#{:02X}{:02X}{:02X}", b[0], b[1], b[2])
}

fn swatch(colour: &str) -> String {
    format!(
        "<span style=\"display:inline-block;width:1.5em;height:1.2em;background:{colour};\
         border:1px solid #888\" title=\"{colour}\"></span>"
    )
}

fn channel(c: Channel) -> &'static str {
    match c {
        Channel::Red => "red (`r`)",
        Channel::Green => "green (`g`)",
        Channel::Blue => "blue (`b`)",
        Channel::Luminance => "all combined (`lum`)",
    }
}

/// Markdown for `reference/presets-table.md`.
pub fn render() -> String {
    let mut out = String::new();
    out.push_str(
        "<!-- Generated by `cargo xtask docs` from crates/helia-core/src/colour.rs. \
         Do not edit. -->\n\n",
    );
    out.push_str(
        "| Id | Filter | Wavelength | Hue | Ramp, black to white | Mid-grey becomes | \
         Bayer channel | Frames kept |\n|---|---|---|---|---|---|---|---|\n",
    );
    for p in Preset::ALL {
        let i = p.info();
        let params = ColourParams::preset(p);
        let ramp: String = [0.0, 0.25, 0.5, 0.75, 1.0]
            .iter()
            .map(|&v| swatch(&hex(params.map_value(v))))
            .collect();
        let mid = hex(params.map_value(0.5));
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {ramp} | {} `{mid}` | {} | {:.0}% |",
            i.id,
            i.name,
            i.wavelength,
            i.hue,
            swatch(&mid),
            channel(i.channel),
            i.keep_percent
        );
    }
    out.push_str("\nWhy each preset recommends what it does:\n\n");
    for p in Preset::ALL {
        let i = p.info();
        let _ = writeln!(out, "* **{}** (`{}`): {}", i.name, i.id, i.reason);
    }
    out.push_str("\nThe numbers behind each colour, for anyone who wants to reproduce it:\n\n");
    out.push_str(
        "| Id | Tone exponent | Gains (R, G, B) | Exponents (R, G, B) |\n|---|---|---|---|\n",
    );
    for p in Preset::ALL {
        let i = p.info();
        let _ = writeln!(
            out,
            "| `{}` | {:.2} | {:.2}, {:.2}, {:.2} | {:.2}, {:.2}, {:.2} |",
            i.id,
            i.gamma,
            i.gains[0],
            i.gains[1],
            i.gains[2],
            i.exponents[0],
            i.exponents[1],
            i.exponents[2]
        );
    }
    out.push_str(
        "
The recommended sharpening of each filter (see Sharpening and adjustments).          Wavelet gains and noise cuts are for layers 1 to 6, finest first; the unsharp          radius comes from the image scale, and the deconvolution blur is measured from          the disc.

",
    );
    out.push_str(
        "| Id | Wavelet gains | Wavelet noise cuts | Unsharp amount | Unsharp threshold |          Deconvolution iterations | TV weight | Denoise |
|---|---|---|---|---|---|---|---|
",
    );
    let list = |v: &[f32]| {
        v.iter()
            .map(|x| format!("{x:.2}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    for p in Preset::ALL {
        let i = p.info();
        let t = &i.sharpen;
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {:.2} | {:.3} | {} | {:.3} | {:.1} |",
            i.id,
            list(&t.gains),
            list(&t.thresholds),
            t.unsharp_amount,
            t.unsharp_threshold,
            t.rl_iterations,
            t.rl_tv,
            t.denoise
        );
    }
    out.push_str(
        "
Why each filter is sharpened the way it is:

",
    );
    for p in Preset::ALL {
        let i = p.info();
        let _ = writeln!(out, "* **{}** (`{}`): {}", i.name, i.id, i.sharpen_reason);
    }
    out
}
