//! Prints `crates/helia-core/src/seeing/table.rs`: the expected ratio
//! `|<S>|^2 / <|S|^2>` of the tilt-free transfer function against `u = f / f_c`
//! for a range of `D / r0`, from Kolmogorov phase screens.
//!
//! `cargo run --release -p helia-core --example seeing_table > src/seeing/table.rs`

use helia_core::seeing::screen::{U_BINS, ratio_curve};
use rayon::prelude::*;

const SCREENS: usize = 600;

fn main() {
    let rho = helia_core::seeing::RHO_GRID;
    let rows: Vec<Vec<f32>> = rho
        .par_iter()
        .enumerate()
        .map(|(i, &r)| ratio_curve(r, SCREENS, 1000 + i as u64))
        .collect();
    println!("// SPDX-FileCopyrightText: 2026 Laurence Horrocks-Barlow");
    println!("// SPDX-License-Identifier: GPL-3.0-or-later");
    println!("// See ADDITIONAL-TERMS.md for terms added under GPLv3 section 7.");
    println!();
    println!("//! Generated by `cargo run --release -p helia-core --example seeing_table`:");
    println!("//! the expected ratio `|<S>|^2 / <|S|^2>` of the tilt-free transfer function of");
    println!("//! a Kolmogorov atmosphere, {SCREENS} phase screens per row. Do not edit.");
    println!();
    println!(
        "/// Rows follow [`super::RHO_GRID`], columns are bins of `u = f / f_c` ({U_BINS} of them)."
    );
    println!("pub const RATIO: [[f32; {U_BINS}]; {}] = [", rho.len());
    for row in rows {
        let cells: Vec<String> = row.iter().map(|v| format!("{v:.5}")).collect();
        println!("    [{}],", cells.join(", "));
    }
    println!("];");
}
